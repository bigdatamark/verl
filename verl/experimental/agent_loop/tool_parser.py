# [MODULE DOC]
# Module tool_parser: pluggable parsers that turn decoded model output into assistant content plus a list of
# FunctionCall objects, one implementation per model chat format (hermes, gpt-oss, qwen3_coder, glm, and others
# below), selected by name from a class-level registry. Decoding runs in the event loop's thread executor.
# Side effects: module logger keyed by file path, level from VERL_LOGGING_LEVEL.
import ast
import json
import logging
import os
from abc import ABC, abstractmethod
from typing import Any, Optional

import regex
from pydantic import BaseModel

from verl.tools.schemas import OpenAIFunctionToolSchema
from verl.utils.ray_utils import get_event_loop
from verl.utils.rollout_trace import rollout_trace_op

logger = logging.getLogger(__file__)
logger.setLevel(os.getenv("VERL_LOGGING_LEVEL", "WARN"))


class FunctionCall(BaseModel):
    # [CLASS DOC]
    # Pydantic model of one parsed tool call: arguments (JSON string, possibly invalid), function name, and optional
    # model-emitted tool call id.
    arguments: str
    """
    The arguments to call the function with, as generated by the model in JSON
    format. Note that the model does not always generate valid JSON, and may
    hallucinate parameters not defined by your function schema. Validate the
    arguments in your code before calling your function.
    """

    name: str
    """The name of the function to call."""

    tool_call_id: Optional[str] = None
    """The model-emitted tool call identifier, if available."""


class ToolParser(ABC):
    # [CLASS DOC]
    # Abstract base for tool parsers. Holds the tokenizer and a class-level registry mapping format name to subclass.
    _registry: dict[str, type["ToolParser"]] = {}

    def __init__(self, tokenizer) -> None:
        # [FUNCTION DOC]
        # Behavior: stores the tokenizer.
        self.tokenizer = tokenizer

    @property
    def stop_token_ids(self) -> list[int]:
        # [FUNCTION DOC]
        # Behavior: default hook returning extra stop token ids for generation. Outputs: empty list.
        """Token IDs that should stop generation so the parser can run.

        Models like Qwen3 naturally emit EOS after a tool call, so no extra stop
        tokens are needed. Models like Gemma4 emit <tool_call|> but continue
        generating without EOS — they need the closing token as an explicit stop.

        Returns empty list by default (rely on model's EOS behavior).
        """
        return []

    @abstractmethod
    async def extract_tool_calls(
        self, responses_ids: list[int], tools: list[OpenAIFunctionToolSchema] = None
    ) -> tuple[str, list[FunctionCall]]:
        # [FUNCTION DOC]
        # Behavior: abstract; subclasses decode responses_ids and extract tool calls. Inputs: token ids; optional tool
        # schemas. Outputs: (content, list of FunctionCall). Exceptions: NotImplementedError if not overridden.
        """Extract tool calls from the responses.

        Args:
            responses_ids (List[int]): The ids of the responses.
            tools (List[OpenAIFunctionToolSchema], optional): OpenAI function tool schema.

        Returns:
            Tuple[str, List[FunctionCall]]: Content and extracted tool calls.
        """
        raise NotImplementedError

    @classmethod
    def get_tool_parser(cls, name: str, tokenizer):
        # [FUNCTION DOC]
        # Behavior: instantiates the registered parser for name with the tokenizer.
        # Exceptions: ValueError for an unknown name.
        if name not in cls._registry:
            raise ValueError(f"Unknown tool parser: {name}")
        return cls._registry[name](tokenizer)

    @classmethod
    def register(cls, name: str):
        # [FUNCTION DOC]
        # Behavior: returns a class decorator that registers the decorated subclass under name (overwriting any prior entry).
        def decorator(subclass: type[ToolParser]) -> type[ToolParser]:
            # [FUNCTION DOC]
            # HELPER: Behavior: stores subclass in the registry and returns it unchanged.
            cls._registry[name] = subclass
            return subclass

        return decorator


@ToolParser.register("hermes")
class HermesToolParser(ToolParser):
    # [CLASS DOC]
    # Hermes-format parser: tool calls are JSON objects with "name" and "arguments" wrapped in tool_call tags.
    """Adapted from https://github.com/vllm-project/vllm/blob/v0.9.1/vllm/entrypoints/openai/tool_parsers/hermes_tool_parser.py"""

    def __init__(self, tokenizer) -> None:
        # [FUNCTION DOC]
        # Behavior: sets start/end tag strings and a non-greedy dot-all regex capturing text between the tags.
        super().__init__(tokenizer)

        self.tool_call_start_token: str = "<tool_call>"
        self.tool_call_end_token: str = "</tool_call>"
        self.tool_call_regex = regex.compile(r"<tool_call>(.*?)</tool_call>", regex.DOTALL)

    @rollout_trace_op
    async def extract_tool_calls(
        self, responses_ids: list[int], tools: list[OpenAIFunctionToolSchema] = None
    ) -> tuple[str, list[FunctionCall]]:
        # [FUNCTION DOC]
        # Behavior: (traced) decodes ids in an executor (default decode settings). If either tag is absent, returns the
        # text and no calls. Otherwise JSON-decodes each tagged block, taking name and arguments (re-serialized as JSON,
        # non-ASCII preserved); malformed blocks are logged and skipped. Content is the text with tagged blocks removed.
        # Inputs: responses_ids; tools unused. Outputs: (content, calls).
        loop = get_event_loop()
        text = await loop.run_in_executor(None, self.tokenizer.decode, responses_ids)
        if self.tool_call_start_token not in text or self.tool_call_end_token not in text:
            return text, []

        matches = self.tool_call_regex.findall(text)
        function_calls = []
        for match in matches:
            try:
                function_call = json.loads(match)
                name, arguments = function_call["name"], function_call["arguments"]
                function_calls.append(FunctionCall(name=name, arguments=json.dumps(arguments, ensure_ascii=False)))
            except Exception as e:
                logger.error(f"Failed to decode tool call: {e}")

        # remaing text exclude tool call tokens
        content = self.tool_call_regex.sub("", text)

        return content, function_calls


@ToolParser.register("gpt-oss")
class GptOssToolParser(ToolParser):
    # [CLASS DOC]
    # gpt-oss (harmony format) parser. Removes analysis-channel chain-of-thought before matching commentary-channel
    # tool calls of the form "to=functions.<name> <|constrain|>json<|message|>ARGS<|call|>".
    """
    Tool parser for gpt-oss model.
    Adapted from https://github.com/sgl-project/sglang/blob/main/python/sglang/srt/function_call/gpt_oss_detector.py

    Args:
        tokenizer: The tokenizer to use.
    """

    def __init__(self, tokenizer) -> None:
        # [FUNCTION DOC]
        # Behavior: compiles patterns for full CoT blocks, partial CoT blocks lacking the assistant start marker, and tool calls.
        super().__init__(tokenizer)
        # check https://cookbook.openai.com/articles/openai-harmony for more details.
        self.cot_pattern = regex.compile(
            r"<\|start\|>assistant<\|channel\|>analysis<\|message\|>.*?<\|end\|>", regex.DOTALL
        )
        # <|start|>assistant may be pre-appended in prompts, so we need to remove it.
        self.partial_cot_pattern = regex.compile(r"<\|channel\|>analysis<\|message\|>(.*?)<\|end\|>", regex.DOTALL)
        self.tool_call_pattern = regex.compile(
            r"<\|start\|>assistant<\|channel\|>[^<]* to=functions\.([^<]+) "
            r"<\|constrain\|>json<\|message\|>(.*?)<\|call\|>",
            regex.DOTALL,
        )

    @rollout_trace_op
    async def extract_tool_calls(
        self, responses_ids: list[int], tools: list[OpenAIFunctionToolSchema] = None
    ) -> tuple[str, list[FunctionCall]]:
        # [FUNCTION DOC]
        # Behavior: (traced) decodes keeping special tokens, removes pad token strings and CoT blocks, finds tool call
        # matches; none -> (text, []). Each match yields a FunctionCall with the raw argument text (not validated).
        # Content is the text with tool call segments removed. Inputs: responses_ids; tools unused. Outputs: (content, calls).
        # Exceptions: TypeError if the tokenizer has no pad token (replace with None).
        loop = get_event_loop()
        # We need to keep special tokens for gpt-oss model for better tool call extraction.
        text = await loop.run_in_executor(None, lambda: self.tokenizer.decode(responses_ids, skip_special_tokens=False))
        # Need to remove padding tokens for better tool call extraction.
        text = text.replace(self.tokenizer.pad_token, "")
        # Need to reomve COT since COT may contain tool call tokens.But they are not valid tool calls.
        text = regex.sub(self.cot_pattern, "", text)
        text = regex.sub(self.partial_cot_pattern, "", text)

        # check if there are tool calls in the text by re.findall
        matches = regex.findall(self.tool_call_pattern, text)
        if not matches:
            return text, []

        function_calls = []
        for match in matches:
            try:
                name, arguments = match[0], match[1]
                # don't check if arguments is valid JSON and leave it to client
                function_calls.append(FunctionCall(name=name, arguments=arguments))
            except Exception as e:
                logger.error(f"Failed to decode tool call: {e}")

        # remaing text exclude tool call tokens
        content = regex.sub(self.tool_call_pattern, "", text)

        return content, function_calls


@ToolParser.register("qwen3_coder")
class Qwen3XMLToolParser(ToolParser):
    # [CLASS DOC]
    # Qwen3-Coder / Qwen3.5 XML parser: tool calls look like tool_call tags containing "<function=NAME>" with nested
    # "<parameter=NAME>VALUE</parameter>" entries; unterminated trailing blocks are tolerated. Parameter values are
    # converted using the tool's JSON schema types.
    """
    Tool parser for qwen3_coder/qwen3.5 model.
    Adapted from https://huggingface.co/Qwen/Qwen3-Coder-30B-A3B-Instruct/blob/main/qwen3coder_tool_parser.py

    Args:
        tokenizer: The tokenizer to use.
    """

    def __init__(self, tokenizer):
        # [FUNCTION DOC]
        # Behavior: sets tag strings and compiles regexes for complete/partial tool_call, function and parameter blocks.
        super().__init__(tokenizer)

        self.tool_call_start_token: str = "<tool_call>"
        self.tool_call_end_token: str = "</tool_call>"
        self.tool_call_prefix: str = "<function="

        self.tool_call_complete_regex = regex.compile(r"<tool_call>(.*?)</tool_call>", regex.DOTALL)
        self.tool_call_regex = regex.compile(r"<tool_call>(.*?)</tool_call>|<tool_call>(.*?)$", regex.DOTALL)
        self.tool_call_function_regex = regex.compile(r"<function=(.*?)</function>|<function=(.*)$", regex.DOTALL)
        self.tool_call_parameter_regex = regex.compile(r"<parameter=(.*?)</parameter>|<parameter=(.*?)$", regex.DOTALL)

    def _parse_xml_function_call(
        self, function_call_str: str, tools: Optional[list[OpenAIFunctionToolSchema]]
    ) -> Optional[FunctionCall]:
        # [FUNCTION DOC]
        # HELPER: Behavior: splits function name at the first ">" (missing -> warn and return None), loads the parameter
        # schema for that function, then for each parameter block splits name/value at ">" (malformed -> warn and skip),
        # strips one leading and one trailing newline, converts the value, and builds a FunctionCall with JSON-serialized
        # arguments. Inputs: raw function body text; optional tool schemas. Outputs: FunctionCall or None.
        tools = tools or []

        def get_arguments_config(func_name: str) -> dict:
            # [FUNCTION DOC]
            # HELPER: Behavior: finds the first function tool whose name matches and returns its parameter properties as plain
            # dicts; logs a warning and returns empty dict if not found.
            for config in tools:
                if config.type == "function" and config.function.name == func_name:
                    properties = config.function.parameters.properties
                    return {k: v.model_dump() for k, v in properties.items()}
            logger.warning(f"Tool '{func_name}' is not defined in the tools list.")
            return {}

        def convert_param_value(param_value: str, param_name: str, param_config: dict, func_name: str) -> Any:
            # [FUNCTION DOC]
            # HELPER: Behavior: converts a string value according to its schema type: "null" (any case) -> None; unknown
            # parameter -> raw string (warning if the schema is non-empty); missing type -> string. String-like types return as-is;
            # int-like types parse as int (fallback string); num/float parse as float, returned as int when integral (fallback
            # string); boolean types return true only for "true" (case-insensitive), warning otherwise; object/dict try JSON
            # first; everything else (and failed JSON) tries a safe Python-literal evaluation, falling back to the string.
            # Outputs: converted value. Side effects: warning logs.
            # Handle null value for any type
            if param_value.lower() == "null":
                return None

            if param_name not in param_config:
                if param_config != {}:
                    logger.warning(
                        f"Parsed parameter '{param_name}' is not defined in the tool "
                        f"parameters for tool '{func_name}', directly returning the string value."
                    )
                return param_value

            if isinstance(param_config[param_name], dict) and "type" in param_config[param_name]:
                param_type = str(param_config[param_name]["type"]).strip().lower()
            else:
                param_type = "string"
            if param_type in ["string", "str", "text", "varchar", "char", "enum"]:
                return param_value
            elif (
                param_type.startswith("int")
                or param_type.startswith("uint")
                or param_type.startswith("long")
                or param_type.startswith("short")
                or param_type.startswith("unsigned")
            ):
                try:
                    param_value = int(param_value)
                except Exception:
                    logger.warning(
                        f"Parsed value '{param_value}' of parameter '{param_name}' is not an integer in tool "
                        f"'{func_name}', degenerating to string."
                    )
                return param_value
            elif param_type.startswith("num") or param_type.startswith("float"):
                try:
                    float_param_value = float(param_value)
                    param_value = (
                        float_param_value if float_param_value - int(float_param_value) != 0 else int(float_param_value)
                    )
                except Exception:
                    logger.warning(
                        f"Parsed value '{param_value}' of parameter '{param_name}' is not a float in tool "
                        f"'{func_name}', degenerating to string."
                    )
                return param_value
            elif param_type in ["boolean", "bool", "binary"]:
                param_value = param_value.lower()
                if param_value not in ["true", "false"]:
                    logger.warning(
                        f"Parsed value '{param_value}' of parameter '{param_name}' is not a "
                        f"boolean (`true` of `false`) in tool '{func_name}', degenerating to false."
                    )
                return param_value == "true"
            else:
                if param_type == "object" or param_type.startswith("dict"):
                    try:
                        param_value = json.loads(param_value)
                        return param_value
                    except Exception:
                        logger.warning(
                            f"Parsed value '{param_value}' of parameter '{param_name}' is not a valid "
                            f"JSON object in tool '{func_name}', will try other methods to parse it."
                        )
                try:
                    # Use ast.literal_eval instead of eval: the parameter value comes from
                    # untrusted model output, and eval() would allow arbitrary code execution.
                    # literal_eval only parses Python literals (lists, tuples, dicts, numbers, ...).
                    param_value = ast.literal_eval(param_value)
                except Exception:
                    logger.warning(
                        f"Parsed value '{param_value}' of parameter '{param_name}' cannot be converted "
                        f"via `ast.literal_eval()` in tool '{func_name}', degenerating to string."
                    )
                return param_value

        # Extract function name. A truncated function header is not recoverable.
        end_index = function_call_str.find(">")
        if end_index == -1:
            logger.warning(f"Skipping malformed function call without '>' separator: {function_call_str!r}")
            return None

        function_name = function_call_str[:end_index]
        param_config = get_arguments_config(function_name)
        parameters = function_call_str[end_index + 1 :]
        param_dict = {}
        for match in self.tool_call_parameter_regex.findall(parameters):
            match_text = match[0] if match[0] else match[1]
            idx = match_text.find(">")
            if idx == -1:
                logger.warning(
                    f"Skipping malformed parameter without '>' separator in tool call for function "
                    f"'{function_name}': {match_text!r}"
                )
                continue

            param_name = match_text[:idx]
            param_value = str(match_text[idx + 1 :])
            # Remove prefix and trailing \n
            if param_value.startswith("\n"):
                param_value = param_value[1:]
            if param_value.endswith("\n"):
                param_value = param_value[:-1]

            param_dict[param_name] = convert_param_value(param_value, param_name, param_config, function_name)
        return FunctionCall(name=function_name, arguments=json.dumps(param_dict, ensure_ascii=False))

    def _get_function_calls(self, model_output: str) -> list[str]:
        # [FUNCTION DOC]
        # HELPER: Behavior: finds all complete or trailing-partial tool_call blocks (if none, treats the whole output as one
        # block), then extracts complete or trailing-partial function blocks from each. Outputs: list of function body strings.
        # Find all tool calls
        matched_ranges = self.tool_call_regex.findall(model_output)
        raw_tool_calls = [match[0] if match[0] else match[1] for match in matched_ranges]

        # Back-off strategy if no tool_call tags found
        if len(raw_tool_calls) == 0:
            raw_tool_calls = [model_output]

        raw_function_calls = []
        for tool_call in raw_tool_calls:
            raw_function_calls.extend(self.tool_call_function_regex.findall(tool_call))

        function_calls = [match[0] if match[0] else match[1] for match in raw_function_calls]
        return function_calls

    @rollout_trace_op
    async def extract_tool_calls(
        self, responses_ids: list[int], tools: list[OpenAIFunctionToolSchema] = None
    ) -> tuple[str, list[FunctionCall]]:
        # [FUNCTION DOC]
        # Behavior: (traced) decodes ids; if the start tag is absent returns (text, []). Otherwise extracts function bodies,
        # parses them dropping failures, and returns the text before the first start tag as content. Any exception is logged
        # and yields (text, []). Inputs: responses_ids; tools used for type conversion.
        loop = get_event_loop()
        text = await loop.run_in_executor(None, self.tokenizer.decode, responses_ids)
        if self.tool_call_start_token not in text:
            return text, []

        try:
            function_calls = self._get_function_calls(text)
            if len(function_calls) == 0:
                return text, []

            tool_calls = [
                self._parse_xml_function_call(function_call_str, tools) for function_call_str in function_calls
            ]
            tool_calls = [tool_call for tool_call in tool_calls if tool_call is not None]

            # Extract content before tool calls
            content_index = text.find(self.tool_call_start_token)
            content_index = content_index if content_index >= 0 else text.find(self.tool_call_prefix)
            content = text[:content_index]  # .rstrip()

            return content, tool_calls
        except Exception as e:
            logger.exception(f"Error in extracting tool call from response: {e}")
            return text, []


@ToolParser.register("glm")
class GLMToolParser(ToolParser):
    # [CLASS DOC]
    # GLM parser: tool_call blocks contain a function name followed by arg_key/arg_value pairs. Uses the observation
    # token as an explicit stop token.
    """Tool parser for GLM XML-style function calls."""

    def __init__(self, tokenizer) -> None:
        # [FUNCTION DOC]
        # Behavior: sets tag/observation tokens and compiles regexes for tool call blocks and key/value pairs.
        super().__init__(tokenizer)
        self.tool_call_start_token = "<tool_call>"
        self.tool_call_end_token = "</tool_call>"
        self.observation_token = "<|observation|>"
        self.tool_call_regex = regex.compile(r"<tool_call>(.*?)</tool_call>", regex.DOTALL)
        self.arg_pair_regex = regex.compile(
            r"<arg_key>(.*?)</arg_key>\s*<arg_value>(.*?)</arg_value>",
            regex.DOTALL,
        )

    @property
    def stop_token_ids(self) -> list[int]:
        # [FUNCTION DOC]
        # Behavior: looks up the observation token id. Outputs: single-element list if it is a non-negative int, else empty.
        token_id = self.tokenizer.convert_tokens_to_ids(self.observation_token)
        if isinstance(token_id, int) and token_id >= 0:
            return [token_id]
        return []

    @staticmethod
    def _convert_arg_value(raw_value: str) -> Any:
        # [FUNCTION DOC]
        # HELPER: Behavior: strips the value and JSON-decodes it, returning the stripped string if decoding fails.
        value = raw_value.strip()
        try:
            return json.loads(value)
        except Exception:
            return value

    def _parse_tool_call(self, tool_call_text: str) -> FunctionCall:
        # [FUNCTION DOC]
        # HELPER: Behavior: name is the text before the first arg_key tag (or the whole stripped text if none); arguments map
        # each stripped key to its converted value. Outputs: FunctionCall with JSON-serialized arguments.
        first_arg_index = tool_call_text.find("<arg_key>")
        if first_arg_index < 0:
            name = tool_call_text.strip()
            arguments: dict[str, Any] = {}
        else:
            name = tool_call_text[:first_arg_index].strip()
            arguments = {
                key.strip(): self._convert_arg_value(value)
                for key, value in self.arg_pair_regex.findall(tool_call_text[first_arg_index:])
            }
        return FunctionCall(name=name, arguments=json.dumps(arguments, ensure_ascii=False))

    @staticmethod
    def _strip_thinking_markers(content: str) -> str:
        # [FUNCTION DOC]
        # HELPER: Behavior: removes a leading (whitespace-prefixed) think...end-think block, then a leading stray end-think tag.
        # Inputs: content text. Outputs: cleaned text.
        content = regex.sub(r"^\s*<think>.*?</think>", "", content, flags=regex.DOTALL)
        content = regex.sub(r"^\s*</think>", "", content)
        return content

    @rollout_trace_op
    async def extract_tool_calls(
        self, responses_ids: list[int], tools: list[OpenAIFunctionToolSchema] = None
    ) -> tuple[str, list[FunctionCall]]:
        # [FUNCTION DOC]
        # Behavior: (traced) decodes keeping special tokens; requires both tool_call tags else (text, []). Parses each tagged
        # block (errors logged and skipped). Content is the text before the first start tag with thinking markers stripped.
        # Inputs: responses_ids; tools ignored. Outputs: (content, calls).
        del tools
        loop = get_event_loop()
        text = await loop.run_in_executor(
            None,
            lambda: self.tokenizer.decode(responses_ids, skip_special_tokens=False),
        )
        if self.tool_call_start_token not in text or self.tool_call_end_token not in text:
            return text, []

        matches = self.tool_call_regex.findall(text)
        function_calls: list[FunctionCall] = []
        for match in matches:
            try:
                function_calls.append(self._parse_tool_call(match))
            except Exception as e:
                logger.error(f"Failed to decode GLM tool call: {e}")

        content_index = text.find(self.tool_call_start_token)
        content = self._strip_thinking_markers(text[:content_index])
        return content, function_calls


@ToolParser.register("seed")
class SeedToolParser(ToolParser):
    # [CLASS DOC]
    # ByteDance Seed parser: seed:tool_call blocks containing "<function=NAME>" with "<parameter=NAME>VALUE</parameter>".
    """Tool parser for ByteDance Seed XML-style function calls."""

    def __init__(self, tokenizer) -> None:
        # [FUNCTION DOC]
        # Behavior: sets tag strings and compiles block, function and parameter regexes.
        super().__init__(tokenizer)
        self.tool_call_start_token = "<seed:tool_call>"
        self.tool_call_end_token = "</seed:tool_call>"
        self.tool_call_regex = regex.compile(r"<seed:tool_call>(.*?)</seed:tool_call>", regex.DOTALL)
        self.function_regex = regex.compile(r"<function=([^>\n]+)>\s*(.*?)</function>", regex.DOTALL)
        self.parameter_regex = regex.compile(r"<parameter=([^>\n]+)>(.*?)</parameter>", regex.DOTALL)

    @staticmethod
    def _convert_parameter_value(raw_value: str) -> Any:
        # [FUNCTION DOC]
        # HELPER: Behavior: strips and JSON-decodes the value, falling back to the stripped string.
        value = raw_value.strip()
        try:
            return json.loads(value)
        except Exception:
            return value

    def _parse_tool_call(self, tool_call_text: str) -> FunctionCall | None:
        # [FUNCTION DOC]
        # HELPER: Behavior: finds the first function block (none -> None), takes the stripped name and maps each stripped
        # parameter name to its converted value. Outputs: FunctionCall or None.
        match = self.function_regex.search(tool_call_text)
        if not match:
            return None

        name = match.group(1).strip()
        body = match.group(2)
        arguments = {
            key.strip(): self._convert_parameter_value(value) for key, value in self.parameter_regex.findall(body)
        }
        return FunctionCall(name=name, arguments=json.dumps(arguments, ensure_ascii=False))

    @rollout_trace_op
    async def extract_tool_calls(
        self, responses_ids: list[int], tools: list[OpenAIFunctionToolSchema] = None
    ) -> tuple[str, list[FunctionCall]]:
        # [FUNCTION DOC]
        # Behavior: (traced) decodes keeping special tokens; requires both tags else (text, []). Parses each block, keeping
        # non-None results and logging errors. Content is the text before the first start tag. Inputs: tools ignored.
        del tools
        loop = get_event_loop()
